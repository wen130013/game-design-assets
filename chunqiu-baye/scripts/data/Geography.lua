------------------------------------------------------------------------
-- Helper: point-in-polygon test (even-odd ray casting)
------------------------------------------------------------------------
function Geography.isPointInPolygon(px, py, polygon)
    local n = #polygon
    if n < 3 then return false end
    local inside = false
    local j = n
    for i = 1, n do
        local xi, yi = polygon[i][1], polygon[i][2]
        local xj, yj = polygon[j][1], polygon[j][2]
        if (yi > py) ~= (yj > py) then
            local intersectX = (xj - xi) * (py - yi) / (yj - yi) + xi
            if px < intersectX then
                inside = not inside
            end
        end
        j = i
    end
    return inside
end

--- Check if a point is on land (inside any zone polygon).
---@param x number
---@param y number
---@return boolean
function Geography.isOnLand(x, y)
    for _, zone in ipairs(Geography.zones) do
        if Geography.isPointInPolygon(x, y, zone.polygon) then
            return true
        end
    end
    return false
end

--- Find which geographic zone a point belongs to.
---@param x number
---@param y number
---@return table|nil
function Geography.getZone(x, y)
    for _, zone in ipairs(Geography.zones) do
        if Geography.isPointInPolygon(x, y, zone.polygon) then
            return zone
        end
    end
    return nil
end

--- Get the density multiplier for a point.
---@param x number
---@param y number
---@return number
function Geography.getDensity(x, y)
    local zone = Geography.getZone(x, y)
    return zone and zone.density or 0.0  -- ocean = 0 density
end

return Geography
