--- 从池子里随机取一项（下标由 #pool 得出，必不为 nil）
---@param pool string[]
---@return string
local function pick(pool)
    return pool[math.random(#pool)] --[[@as string]]
end

--- 随机一个名（1~2 字）
---@return string
local function randomGiven()
    local a = pick(Names.GIVEN_A)
    -- 三成单字名，七成双字名（单字更古）
    if math.random() < 0.3 then return a end
    return a .. pick(Names.GIVEN_B)
end

--- 随机一个姓（单姓 9 : 复姓 1）
---@return string
local function randomSurname()
    if math.random() < 0.1 then
        return pick(Names.SURNAMES_TWO)
    end
    return pick(Names.SURNAMES_ONE)
end

--- 随机一位"提议人"（名 + 身份；身份有官职 / 非官职两种）
---@return table { name = string, title = string, who = string }
function Names.randomPerson()
    local name = randomSurname() .. randomGiven()
    -- 一半是"有官职的"，一半是"没官职的"（用户："可能是什么官职也可能不是"）
    local title
    if math.random() < 0.5 then
        title = pick(Names.TITLES)
    else
        title = pick(Names.NON_TITLES)
    end
    return { name = name, title = title, who = title .. name }
end

--- 只取一个随机人名（不带身份）
---@return string
function Names.randomName()
    return randomSurname() .. randomGiven()
end

return Names
